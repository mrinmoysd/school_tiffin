#!/usr/bin/env node

const fs = require('fs');

const COMMIT_TYPES = new Set([
  'feat',
  'fix',
  'docs',
  'style',
  'refactor',
  'test',
  'chore',
  'perf',
  'ci',
  'revert',
]);

const TYPE_MAP = {
  feature: 'feat',
  feat: 'feat',
  fix: 'fix',
  bugfix: 'fix',
  docs: 'docs',
  doc: 'docs',
  style: 'style',
  refactor: 'refactor',
  test: 'test',
  chore: 'chore',
  perf: 'perf',
  ci: 'ci',
  revert: 'revert',
};

function splitSubject(prefix, subject, limit) {
  const words = subject.trim().split(/\s+/).filter(Boolean);
  if (words.length === 0) {
    return { header: `${prefix}update`, remainder: '' };
  }

  let kept = '';
  let used = 0;
  for (let i = 0; i < words.length; i += 1) {
    const candidate = kept ? `${kept} ${words[i]}` : words[i];
    if ((prefix + candidate).length <= limit) {
      kept = candidate;
      used = i + 1;
    } else {
      break;
    }
  }

  if (!kept) {
    const room = Math.max(1, limit - prefix.length - 3);
    const cut = subject.slice(0, room).trimEnd();
    return { header: `${prefix}${cut}...`, remainder: subject.slice(cut.length).trim() };
  }

  return {
    header: `${prefix}${kept}`.trimEnd(),
    remainder: words.slice(used).join(' '),
  };
}

function normalizeHeader(header) {
  const conventional = /^(?<type>[a-z]+)(?<scope>\([^)]+\))?(?<bang>!)?:\s*(?<subject>.+)$/i.exec(
    header,
  );

  if (conventional && COMMIT_TYPES.has(conventional.groups.type.toLowerCase())) {
    const type = conventional.groups.type.toLowerCase();
    const scope = conventional.groups.scope || '';
    const bang = conventional.groups.bang || '';
    const subject = conventional.groups.subject.trim();
    const prefix = `${type}${scope}${bang}: `;
    return { prefix, subject };
  }

  const firstToken = header
    .split(/[\s:]/)[0]
    .toLowerCase()
    .replace(/[^a-z]/g, '');
  const inferredType = TYPE_MAP[firstToken] || 'chore';
  let subject = header.replace(/^[^:\s-]+[:\s-]*/, '').trim();
  if (!subject) {
    subject = 'update project files';
  }
  return { prefix: `${inferredType}: `, subject };
}

function wrapText(text, max) {
  const words = text.split(/\s+/).filter(Boolean);
  const out = [];
  let line = '';
  for (const word of words) {
    const candidate = line ? `${line} ${word}` : word;
    if (candidate.length <= max) {
      line = candidate;
    } else {
      if (line) out.push(line);
      if (word.length > max) {
        out.push(word.slice(0, max));
        line = word.slice(max);
      } else {
        line = word;
      }
    }
  }
  if (line) out.push(line);
  return out;
}

function appendRemainderBody(existingBody, remainder) {
  if (!remainder) {
    return existingBody;
  }

  const lines = [...existingBody];
  const detailLines = wrapText(remainder, 91); // "Details: " + 91 = 100
  const prefixed = detailLines.map((line, i) =>
    i === 0 ? `Details: ${line}` : `         ${line}`,
  );
  return ['', ...prefixed, ...lines];
}

function main() {
  const msgFile = process.argv[2];
  if (!msgFile || !fs.existsSync(msgFile)) {
    process.exit(0);
  }

  const raw = fs.readFileSync(msgFile, 'utf8');
  if (!raw.trim()) {
    process.exit(0);
  }

  const lines = raw.split(/\r?\n/);
  const header = (lines[0] || '').trim();

  // Skip merge/squash/fixup autogenerated commit messages.
  if (header.startsWith('Merge ') || header.startsWith('fixup!') || header.startsWith('squash!')) {
    process.exit(0);
  }

  const { prefix, subject } = normalizeHeader(header);
  const { header: normalizedHeader, remainder } = splitSubject(prefix, subject, 100);
  const bodyLines = lines.slice(1);
  const normalizedBody = appendRemainderBody(bodyLines, remainder);

  const output = [normalizedHeader, ...normalizedBody].join('\n').replace(/\n+$/, '\n');
  fs.writeFileSync(msgFile, output, 'utf8');
}

main();
